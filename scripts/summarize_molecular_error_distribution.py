#!/usr/bin/env python3
"""Reproduce the paper's distribution statistics from the frozen common set."""

import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "benchmarks/dietGMTKN55/production-p25/paper-common-70"
SOURCE = DATA / "native-protocol-comparison.csv"
PROTOCOLS = {
    "GX": "gapwxc_gth",
    "HD": "hybrid_ae_gth_direct",
    "HOC": "hybrid_ae_gth_one_center",
}


def main():
    with SOURCE.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    keys = [(row["subset"], row["reaction_id"]) for row in rows]
    assert len(rows) == len(set(keys)) == 70
    summary = {
        "source": str(SOURCE.relative_to(ROOT)),
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "reaction_count": len(rows),
        "parent_subset_count": len({row["subset"] for row in rows}),
        "units": "kcal/mol",
        "protocols": {},
    }
    tails = set()
    for name, prefix in PROTOCOLS.items():
        errors = [float(row[prefix + "_error_kcal_mol"]) for row in rows]
        ranked = sorted(range(len(rows)), key=lambda i: abs(errors[i]), reverse=True)
        tails.update(ranked[:3])
        summary["protocols"][name] = {
            "count_absolute_error_below_1": sum(abs(e) < 1 for e in errors),
            "count_absolute_error_below_2": sum(abs(e) < 2 for e in errors),
            "count_absolute_error_above_5": sum(abs(e) > 5 for e in errors),
            "largest_error_reaction": "/".join(keys[ranked[0]]),
            "largest_error_fraction_of_sum_squared_errors": (
                errors[ranked[0]] ** 2 / sum(e * e for e in errors)
            ),
        }
    summary["largest_error_union"] = [
        {
            "reaction": "/".join(keys[i]),
            "signed_errors": {
                name: float(rows[i][prefix + "_error_kcal_mol"])
                for name, prefix in PROTOCOLS.items()
            },
        }
        for i in sorted(tails, key=lambda i: keys[i])
    ]
    (DATA / "error-distribution-summary.json").write_text(
        json.dumps(summary, indent=2) + "\n"
    )
    tex = [
        "% Generated by scripts/summarize_molecular_error_distribution.py.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Error distribution on the unchanged 70-reaction common set. "
        r"GX is \texttt{GAPW\_XC}--\GTH{}; HD and HOC are mixed "
        r"\GAPW{}-AE/\GTH{} with direct and one-center fields. The upper panel "
        r"counts reactions at fixed absolute-error thresholds; the lower panel "
        r"lists the union of the three largest absolute errors of each protocol, "
        r"with signed errors in $\mathrm{kcal\,mol^{-1}}$.}",
        r"\label{tab:molecular-error-distribution}",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Statistic or reaction & GX & HD & HOC \\",
        r"\midrule",
    ]
    for label, field in [
        (r"Number with $|\Delta E|<1$", "count_absolute_error_below_1"),
        (r"Number with $|\Delta E|<2$", "count_absolute_error_below_2"),
        (r"Number with $|\Delta E|>5$", "count_absolute_error_above_5"),
    ]:
        values = [str(summary["protocols"][name][field]) for name in PROTOCOLS]
        tex.append(label + " & " + " & ".join(values) + r" \\")
    tex.append(r"\midrule")
    for row in summary["largest_error_union"]:
        values = [f"${row['signed_errors'][name]:+.4f}$" for name in PROTOCOLS]
        tex.append(row["reaction"] + " & " + " & ".join(values) + r" \\")
    tex.extend([r"\bottomrule", r"\end{tabular}", r"\end{table*}"])
    (DATA / "molecular-distribution-si.tex").write_text("\n".join(tex) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
